
-- =========================================
-- 1. USERS - TÀI KHOẢN NGƯỜI DÙNG
-- =========================================

CREATE TABLE IF NOT EXISTS users (
                                     username VARCHAR(64) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    avatar_file VARCHAR(80),
    avatar_content_type VARCHAR(100),
    display_name VARCHAR(100),
    created_at BIGINT NOT NULL
    );


-- =========================================
-- 2. ROOMS - PHÒNG CHAT NHÓM
-- =========================================

CREATE TABLE IF NOT EXISTS rooms (
                                     room_id VARCHAR(36) PRIMARY KEY,
    room_name VARCHAR(100) NOT NULL,
    created_by VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE RESTRICT,
    created_at BIGINT NOT NULL,
    deleted_at BIGINT
    );


-- =========================================
-- 3. ROOM_MEMBERS - THÀNH VIÊN NHÓM
-- =========================================

CREATE TABLE IF NOT EXISTS room_members (
                                            room_id VARCHAR(36) NOT NULL
    REFERENCES rooms(room_id) ON DELETE CASCADE,

    username VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE CASCADE,

    joined_at BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'MEMBER',
    left_at BIGINT,

    PRIMARY KEY (room_id, username)
    );


-- =========================================
-- 4. DIRECT_CONVERSATIONS - CUỘC TRÒ CHUYỆN CÁ NHÂN
-- =========================================

CREATE TABLE IF NOT EXISTS direct_conversations (
                                                    conversation_id VARCHAR(36) PRIMARY KEY,

    participant_a VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE CASCADE,

    participant_b VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE CASCADE,

    created_at BIGINT NOT NULL,
    last_message_at BIGINT NOT NULL,

    UNIQUE (participant_a, participant_b),

    CHECK (participant_a <> participant_b)
    );


-- =========================================
-- 5. CHAT_FILES - FILE ĐÍNH KÈM NHÓM VÀ CÁ NHÂN
-- =========================================

CREATE TABLE IF NOT EXISTS chat_files (
                                          file_id VARCHAR(36) PRIMARY KEY,

    -- File nhóm: room_id có giá trị
    -- File cá nhân: room_id = NULL
    room_id VARCHAR(36)
    REFERENCES rooms(room_id) ON DELETE CASCADE,

    -- File cá nhân: conversation_id có giá trị
    -- File nhóm: conversation_id = NULL
    conversation_id VARCHAR(36)
    REFERENCES direct_conversations(conversation_id)
                              ON DELETE CASCADE,

    uploaded_by VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE RESTRICT,

    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(150) NOT NULL,
    storage_name VARCHAR(80) NOT NULL,
    created_at BIGINT NOT NULL,

    -- Một file chỉ thuộc một loại cuộc trò chuyện
    CONSTRAINT chk_chat_files_conversation_type
    CHECK (
(room_id IS NOT NULL AND conversation_id IS NULL)
    OR
(room_id IS NULL AND conversation_id IS NOT NULL)
    )
    );


-- =========================================
-- 6. MESSAGES - TIN NHẮN NHÓM
-- =========================================

CREATE TABLE IF NOT EXISTS messages (
                                        message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                        room_id VARCHAR(36) NOT NULL
    REFERENCES rooms(room_id) ON DELETE CASCADE,

    sender_username VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE RESTRICT,

    content TEXT NOT NULL,

    file_id VARCHAR(36)
    REFERENCES chat_files(file_id) ON DELETE SET NULL,

    recalled BOOLEAN NOT NULL DEFAULT FALSE,

    created_at BIGINT NOT NULL
    );


-- =========================================
-- 7. MESSAGE_READ_RECEIPTS - TRẠNG THÁI ĐỌC TIN NHẮN NHÓM
-- =========================================

CREATE TABLE IF NOT EXISTS message_read_receipts (
                                                     message_id BIGINT NOT NULL
                                                     REFERENCES messages(message_id) ON DELETE CASCADE,

    username VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE CASCADE,

    read_at BIGINT NOT NULL,

    PRIMARY KEY (message_id, username)
    );


-- =========================================
-- 8. DIRECT_MESSAGES - TIN NHẮN CÁ NHÂN
-- =========================================

CREATE TABLE IF NOT EXISTS direct_messages (
                                               message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                               conversation_id VARCHAR(36) NOT NULL
    REFERENCES direct_conversations(conversation_id) ON DELETE CASCADE,

    sender_username VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE RESTRICT,

    content TEXT NOT NULL,

    file_id VARCHAR(36)
    REFERENCES chat_files(file_id) ON DELETE SET NULL,

    recalled BOOLEAN NOT NULL DEFAULT FALSE,

    created_at BIGINT NOT NULL
    );


-- =========================================
-- 9. DIRECT_MESSAGE_READ_RECEIPTS - TRẠNG THÁI ĐỌC TIN NHẮN CÁ NHÂN
-- =========================================

CREATE TABLE IF NOT EXISTS direct_message_read_receipts (
                                                            message_id BIGINT NOT NULL
                                                            REFERENCES direct_messages(message_id) ON DELETE CASCADE,

    username VARCHAR(64) NOT NULL
    REFERENCES users(username) ON DELETE CASCADE,

    read_at BIGINT NOT NULL,

    PRIMARY KEY (message_id, username)
    );


-- =========================================
-- 10. INDEX - TỐI ƯU TRUY VẤN
-- =========================================

CREATE INDEX IF NOT EXISTS idx_messages_room_id
    ON messages(room_id, message_id);

CREATE INDEX IF NOT EXISTS idx_room_members_username
    ON room_members(username, left_at);

CREATE INDEX IF NOT EXISTS idx_direct_messages_conversation
    ON direct_messages(conversation_id, message_id);

CREATE INDEX IF NOT EXISTS idx_chat_files_conversation
    ON chat_files(conversation_id);

CREATE INDEX IF NOT EXISTS idx_chat_files_room
    ON chat_files(room_id);

CREATE INDEX IF NOT EXISTS idx_direct_messages_file
    ON direct_messages(file_id);

CREATE INDEX IF NOT EXISTS idx_messages_file
    ON messages(file_id);


-- =========================================
-- 11. CẬP NHẬT DỮ LIỆU MẶC ĐỊNH
-- =========================================

UPDATE users
SET display_name = username
WHERE display_name IS NULL;

UPDATE room_members
SET role = 'LEADER'
WHERE username IN (
    SELECT created_by
    FROM rooms
    WHERE rooms.room_id = room_members.room_id
);
